import { pageLabel } from '@/domain/note/note-text';
import type { NoteChunk } from '@/domain/note/note.schema';
import {
  COSINE_FLOOR,
  MIN_SHARED_WORDS,
  TOP_K,
  retrieve,
} from '@/domain/note/retrieve';
import {
  findSentence,
  loadRetrievalSpec,
  resolveTarget,
} from '@/eval/eval-context';
import type { EvalContext } from '@/eval/eval.types';

type RankKey = 'keywordRank' | 'meaningRank' | 'fusedRank';

const bestOf = (ranks: Array<number | null>): number | null => {
  const real = ranks.filter((r): r is number => r !== null);
  return real.length ? Math.min(...real) : null;
};
const show = (rank: number | null): string =>
  rank === null ? '–' : String(rank);

export async function retrievalTableMarkdown(
  ctx: EvalContext,
): Promise<string> {
  const { index } = ctx;
  const spec = await loadRetrievalSpec();
  const chunksContaining = (phrases: ReadonlyArray<string>): Array<NoteChunk> =>
    phrases.map((phrase) => findSentence(index, phrase).chunk);
  const embed = async (text: string): Promise<Array<number> | null> =>
    (await ctx.models.embed([text], 'query'))?.[0] ?? null;

  const rows: Array<string> = [];
  const summary = {
    goldInTop: 0,
    total: 0,
    distractorAboveGold: 0,
    fusedBeatsBoth: 0,
  };
  const withoutQuote = new Map<string, number | null>();
  const quoteEffect = { better: 0, worse: 0, same: 0 };
  const floorData: Array<{
    what: string;
    shared: number;
    cosine: number | null;
    noSupport: boolean;
  }> = [];

  for (const withQuote of [false, true]) {
    for (const t of spec.targets) {
      const target = resolveTarget(ctx, t.source);
      const extra = withQuote ? spec.quotes[t.id] : undefined;
      const run = retrieve(index, {
        target,
        extra,
        vector: await embed(`${target} ${extra ?? ''}`.trim()),
      });
      const rank = (chunks: Array<NoteChunk>, key: RankKey): number | null =>
        bestOf(
          chunks.map(
            (c) => run.ranking.find((r) => r.chunk.id === c.id)?.[key] ?? null,
          ),
        );
      const gold = chunksContaining(t.gold);
      const distractors = chunksContaining(t.distractor);
      const goldFused = rank(gold, 'fusedRank');
      const distractorFused = distractors.length
        ? rank(distractors, 'fusedRank')
        : null;
      if (withQuote) {
        const before = withoutQuote.get(t.id) ?? null;
        if (before !== null && goldFused !== null) {
          if (goldFused < before) quoteEffect.better++;
          else if (goldFused > before) quoteEffect.worse++;
          else quoteEffect.same++;
        }
      } else {
        withoutQuote.set(t.id, goldFused);
        const k = rank(gold, 'keywordRank');
        const m = rank(gold, 'meaningRank');
        if (
          goldFused !== null &&
          k !== null &&
          m !== null &&
          goldFused < Math.min(k, m)
        )
          summary.fusedBeatsBoth++;
        summary.total++;
        if (goldFused !== null && goldFused <= TOP_K) summary.goldInTop++;
        if (
          distractorFused !== null &&
          goldFused !== null &&
          distractorFused < goldFused
        )
          summary.distractorAboveGold++;
        floorData.push({
          what: t.id,
          shared: run.best.sharedWords,
          cosine: run.best.cosine,
          noSupport: run.noSupport,
        });
      }
      rows.push(
        `| ${t.id} | ${withQuote ? 'yes' : 'no'} | ${show(rank(gold, 'keywordRank'))} | ${show(rank(gold, 'meaningRank'))} | **${show(goldFused)}** | ${
          distractors.length
            ? `${show(rank(distractors, 'keywordRank'))} / ${show(rank(distractors, 'meaningRank'))} / ${show(distractorFused)}`
            : '–'
        } | ${[...new Set(run.results.flatMap((r) => r.chunk.pages))].sort((a, b) => a - b).join(', ')} | ${pageLabel(gold[0]?.pages ?? [])} |`,
      );
    }
  }

  for (const text of spec.unsupported) {
    const run = retrieve(index, { target: text, vector: await embed(text) });
    floorData.push({
      what: `unsupported: "${text}"`,
      shared: run.best.sharedWords,
      cosine: run.best.cosine,
      noSupport: run.noSupport,
    });
  }

  const mode = index.embedding
    ? `keyword + ${index.embedding.model}`
    : 'keyword only (no embeddings in the index)';
  return `# Retrieval comparison

Generated by \`pnpm retrieval-table\` on ${new Date().toISOString().slice(0, 10)} from the committed index
(${index.chunks.length} passages; ${mode}). No language model is involved, so this table is exactly repeatable.

For each target, the rank of the best supporting passage under each kind of search (1 is best).
"Fused" is what the app uses; it keeps the top ${TOP_K}. The distractor column gives the rank of the
best wrong-context passage as keyword / meaning / fused.

| Target | Trainee's words added | Keyword | Meaning | Fused | Distractor (k / m / f) | Pages in the top ${TOP_K} | Gold page |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

**Without the trainee's words:** the supporting passage is in the fused top ${TOP_K} for ${summary.goldInTop} of ${summary.total} targets.
A distractor outranks it for ${summary.distractorAboveGold} of ${summary.total}. The fused rank is better than both
single searches for ${summary.fusedBeatsBoth} of ${summary.total}.

**Adding the trainee's own words to the search:** the supporting passage ranked better for ${quoteEffect.better},
worse for ${quoteEffect.worse} and the same for ${quoteEffect.same} of ${summary.total} targets. With no consistent gain, the app
searches with the missed key point alone.

## The "no support" floor

A target is refused before any model is called only when BOTH hold: fewer than ${MIN_SHARED_WORDS} content words
shared with every passage, and the closest passage by meaning scores under ${COSINE_FLOOR}.

| Target | Most words shared with any passage | Closest by meaning | Refused |
|---|---|---|---|
${floorData.map((f) => `| ${f.what} | ${f.shared} | ${f.cosine ?? '–'} | ${f.noSupport ? 'yes' : 'no'} |`).join('\n')}

**What this shows.** The last four rows are invented key points the note does not cover. Their
scores overlap the real ones, so no cut-off on these two numbers separates "covered" from "not
covered" on this note. The floor is therefore kept only as a guard against a target that is wholly
off-topic. The decision "no support" is made later, by the step that picks the supporting sentence
and by the separate support check, and how reliably they make it is measured in the checks.
`;
}
