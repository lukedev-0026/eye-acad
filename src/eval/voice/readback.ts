import { writeFile } from 'node:fs/promises';

import { buildCatalogue } from '@/domain/examiner/catalogue';
import { renderFinding, renderHistory } from '@/domain/examiner/render';
import type { RenderedItem } from '@/domain/examiner/render';
import type { Print } from '@/eval/cli';
import { PATHS, resultsFile } from '@/eval/paths';
import { appendRow } from '@/eval/run/results.store';
import { loadCase } from '@/infrastructure/files/case-file.loader';
import { STT_LANGUAGE } from '@/infrastructure/speech/deepgram-speech.service';
import type { DeepgramSpeechService } from '@/infrastructure/speech/deepgram-speech.service';

import { problemsHeard } from './heard-back';

export interface ReadbackOptions {
  readonly runs: number;
  readonly only?: string | undefined;
}

export interface ReadbackRow {
  readonly id: string;
  readonly run: number;
  readonly pass: boolean;
  readonly problems: Array<string>;
  readonly said: string;
  readonly heard: string;
}

/** Speaks each finding, transcribes it, checks the eye, numbers and unit. */
export async function runReadback(
  voice: DeepgramSpeechService,
  options: ReadbackOptions,
  print: Print,
): Promise<void> {
  const c = await loadCase();
  const keyterms = buildCatalogue(c).names;
  const items: Array<{ item: RenderedItem; unit: string | null }> = [
    ...c.findings.map((f) => ({
      item: renderFinding(f),
      unit: f.available ? f.unit : null,
    })),
    ...Object.entries(c.patient).map(([k, v]) => ({
      item: renderHistory(k, v),
      unit: null,
    })),
  ].filter((x) => !options.only || x.item.id === options.only);

  const runId = `readback-${new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)}`;
  const rows: Array<ReadbackRow> = [];

  for (let run = 1; run <= options.runs; run++) {
    for (const { item, unit } of items) {
      const problems: Array<string> = [];
      const speech = await voice.synthesise(item.speech);
      let heard = '';
      if (!speech)
        problems.push(`speech could not be produced (${voice.lastError})`);
      else {
        const stt = await voice.transcribe(
          Buffer.from(speech.audioBase64, 'base64'),
          speech.mimeType,
          keyterms,
        );
        if (!stt.ok)
          problems.push(`audio could not be transcribed (${stt.error})`);
        else heard = stt.text;
      }
      if (heard) problems.push(...problemsHeard(item, unit, heard));

      const row: ReadbackRow = {
        id: item.id,
        run,
        pass: problems.length === 0,
        problems,
        said: item.speech,
        heard,
      };
      rows.push(row);
      await appendRow(runId, {
        type: 'readback',
        runId,
        at: new Date().toISOString(),
        voice: voice.voice,
        language: STT_LANGUAGE,
        ...row,
      });
      if (options.only) {
        print(
          `said : ${item.speech}\nheard: ${heard}\n${problems.length ? `PROBLEMS: ${problems.join('; ')}` : 'ok'}`,
        );
      } else {
        process.stdout.write(row.pass ? '.' : 'x');
      }
    }
  }

  if (options.only) return;
  const summary = summariseReadback(rows);
  await writeFile(
    PATHS.readback,
    readbackMarkdown(rows, { runId, runs: options.runs, voice: voice.voice }),
  );
  print(
    `\n${summary.everyRun.length} of ${summary.ids.length} sentences passed on every one of ${options.runs} runs (${summary.passedRuns} of ${rows.length} runs). Eye not heard: ${summary.eyeLost.length} runs. No audio: ${summary.noAudio.length} runs. Wrote ${PATHS.readback}`,
  );
  for (const r of summary.failing)
    print(
      `  ${r.id} (run ${r.run}): ${r.problems.join('; ')}\n    heard: ${r.heard}`,
    );
}

function summariseReadback(rows: ReadonlyArray<ReadbackRow>) {
  const ids = [...new Set(rows.map((r) => r.id))];
  const failing = rows.filter((r) => !r.pass);
  return {
    ids,
    everyRun: ids.filter((id) =>
      rows.filter((r) => r.id === id).every((r) => r.pass),
    ),
    failing,
    passedRuns: rows.filter((r) => r.pass).length,
    eyeLost: failing.filter((r) => r.problems.some((p) => p.includes('eye'))),
    noAudio: failing.filter((r) =>
      r.problems.some((p) => p.startsWith('speech could not')),
    ),
  };
}

function readbackMarkdown(
  rows: ReadonlyArray<ReadbackRow>,
  meta: { runId: string; runs: number; voice: string },
): string {
  const s = summariseReadback(rows);
  return [
    '# Spoken read-back check',
    '',
    `Generated by \`pnpm readback\` on ${new Date().toISOString().slice(0, 10)} from \`${resultsFile(meta.runId)}\`.`,
    `Each sentence the examiner can say about the case was turned into audio (voice \`${meta.voice}\`), and the audio was turned back into text (${STT_LANGUAGE}), ${meta.runs} times. The check is that the eye, every number and the unit are in what was heard.`,
    '',
    `**${s.everyRun.length} of ${s.ids.length} sentences passed on every one of ${meta.runs} runs** (${s.passedRuns} of ${rows.length} individual runs).`,
    `Runs where the eye was not heard correctly: ${s.eyeLost.length}. Runs where no audio was produced: ${s.noAudio.length}.`,
    '',
    ...(s.failing.length
      ? [
          '| Row | Run | What went missing | Said | Heard back |',
          '|---|---|---|---|---|',
          ...s.failing.map(
            (r) =>
              `| ${r.id} | ${r.run} | ${r.problems.join('; ')} | ${r.said} | ${r.heard} |`,
          ),
          '',
        ]
      : []),
    'A failure here can be the voice saying it wrongly or the transcription hearing it wrongly. The table shows both sides so a person can listen and tell which.',
    '',
  ].join('\n');
}
