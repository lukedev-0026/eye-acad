// Writes evals/cases/REVIEW.md: every hand-written case with its expected
// answer, laid out for a person to read and correct. The expected answers are
// judgement calls and the settings are chosen against them.
//   pnpm tsx scripts/cases-review.ts
import { writeFile } from 'node:fs/promises';

import { coverageItems } from '@/application/steps/coverage.step';
import { headingPath, pageLabel } from '@/domain/note/note.types';
import { findSentence, loadContext, readCases, resolveTarget } from '@/eval/eval-context';

const ctx = await loadContext();
const cell = (t: string) => t.replaceAll('|', '\\|').replace(/\s+/g, ' ').trim();
const out: Array<string> = [];
const split = (s: string) => (s === 'tune' ? 'tuning' : 'held back');

out.push('# Expected answers, for a person to read', '');
out.push(
  'Generated by `pnpm tsx scripts/cases-review.ts` from the files in this folder. Every expected answer below is a judgement call, written with an AI assistant from the case file and the reference note. The settings are chosen against them, so they are worth reading.',
  '',
  '**If you disagree with one, note the case id and what it should be.** The correction goes into the case file and into `CORRECTIONS.md`, and every recorded result is re-scored from the stored model replies. Nothing has to be re-run.',
  '',
);

// ---- selector
type Sel = { utterance: string; previous?: Array<{ item: string; eye: string }> };
type SelE = { kind: string; ids?: Array<string>; acceptKinds?: Array<string>; alsoNotRecorded?: boolean };
const selector = await readCases<Sel, SelE>('selector.jsonl');
out.push(`## 1. Menu-picker: ${selector.length} requests`, '');
out.push(
  'What the trainee says, and what the examiner should then do. "Reveal" lists the rows that should be shown; anything else means nothing is revealed.',
  '',
);
out.push('| Case | Set | Kind of request | The trainee says | Expected | Note |', '|---|---|---|---|---|---|');
for (const c of selector) {
  const prev = c.input.previous?.length
    ? ` _(after asking for ${c.input.previous.map((p) => `${p.item}, ${p.eye}`).join('; ')})_`
    : '';
  const expected =
    c.expect.kind === 'reveal'
      ? `Reveal: ${(c.expect.ids ?? []).join(', ')}${c.expect.alsoNotRecorded ? ' and say something else is not recorded' : ''}`
      : `${{ not_recorded: 'Say it is not recorded', too_many: 'Ask for specific findings', wants_to_answer: 'Point to the Give my answer button', other: 'Ask for a finding' }[c.expect.kind] ?? c.expect.kind}` +
        (c.expect.acceptKinds?.length ? ` (also fine: ${c.expect.acceptKinds.join(', ')})` : '');
  out.push(
    `| ${c.id} | ${split(c.split)} | ${c.type} | ${cell(c.input.utterance)}${prev} | ${expected} | ${cell(c.note ?? '')} |`,
  );
}
out.push('');

// ---- coverage
type CovE = { acceptableTargets: Array<string>; statuses: Record<string, string> };
const items = coverageItems(ctx.notes);
const coverage = await readCases<{ answer: string }, CovE>('coverage.jsonl');
out.push(`## 2. Coverage judge: ${coverage.length} sample answers`, '');
out.push(
  'For each sample answer: is each item covered, partly covered or not covered ("either" means a careful marker could go two ways, and that pair is left out of the count). "Acceptable gap" is what the trainee could reasonably be shown as the thing to revise.',
  '',
);
out.push(
  'The items:',
  '',
  ...items.map((i) => `- **${i.id}** (${i.kind === 'diagnosis' ? 'the diagnosis' : 'key point'}): ${i.text}`),
  '',
);
for (const c of coverage) {
  out.push(`### ${c.id} (${split(c.split)}, ${c.type})`, '', `> ${c.input.answer}`, '');
  out.push(
    '| ' + items.map((i) => i.id).join(' | ') + ' | Acceptable gap |',
    '|' + items.map(() => '---').join('|') + '|---|',
  );
  out.push(
    '| ' +
      items.map((i) => c.expect.statuses[i.id].replace('_', ' ')).join(' | ') +
      ` | ${c.expect.acceptableTargets.join(', ')} |`,
  );
  if (c.note) out.push('', `_Note: ${c.note}_`);
  out.push('');
}

// ---- verifier
const verifier = await readCases<{ statement: string; cite: string }, { verdict: string }>('verifier.jsonl');
out.push(`## 3. Support check: ${verifier.length} pairs`, '');
out.push('Does the quoted sentence, read where it sits in the note, back the advice?', '');
out.push(
  '| Case | Set | Advice | Quoted sentence | Where it sits | Expected | Note |',
  '|---|---|---|---|---|---|---|',
);
for (const c of verifier) {
  const { chunk, sentence } = findSentence(ctx.index, c.input.cite);
  out.push(
    `| ${c.id} | ${split(c.split)} | ${cell(c.input.statement)} | “${cell(sentence.column ? `${sentence.column}: ${sentence.text}` : sentence.text)}” | ${pageLabel(sentence.pages)}, ${cell(headingPath(chunk))}${chunk.leadIn ? ` — ${cell(chunk.leadIn)}` : ''} | **${c.expect.verdict.replace('_', ' ')}** | ${cell(c.note ?? '')} |`,
  );
}
out.push('');

// ---- revision
const revision = await readCases<{ target: string; exclude: string }, { support: boolean; targetId?: string }>(
  'revision.jsonl',
);
out.push(`## 4. Revision step: ${revision.length} points to revise`, '');
out.push(
  'For each point: the sentences of the note that count as backing it. "Main source" is in the acute primary angle closure material. "Also backs it" is accepted too. "Outside the main section" backs the point but is not where the case author said to cite from. "Wrong context" mentions the same words about something else, and quoting it is the costly error. Where the supporting passages are removed, or the point is invented, the right answer is "no support".',
  '',
);
for (const c of revision) {
  const text = resolveTarget(ctx, c.input.target);
  const t = ctx.targets.find((x) => x.id === c.expect.targetId);
  out.push(`### ${c.id} (${split(c.split)}, ${c.type})`, '', `**Point:** ${text}`, '');
  out.push(
    `**Expected:** ${c.expect.support ? 'supported, quoting a main-source or also-backs-it sentence' : `no support${c.input.exclude === 'all_support' ? ' (every sentence listed below as backing it is removed from the search first)' : ''}`}`,
    '',
  );
  if (t) {
    const list = (title: string, phrases: Array<string>) => {
      if (!phrases.length) return;
      out.push(`- ${title}:`);
      for (const p of phrases) {
        const { sentence } = findSentence(ctx.index, p);
        out.push(
          `  - ${pageLabel(sentence.pages)}: “${sentence.column ? `${sentence.column}: ` : ''}${sentence.text}”`,
        );
      }
    };
    list('Main source', t.gold);
    list('Also backs it', t.alsoSupports);
    list('Outside the main section', t.offSection ?? []);
    list('Wrong context', t.distractor);
  }
  if (c.note) out.push('', `_Note: ${c.note}_`);
  out.push('');
}

// ---- follow-up
const followup = await readCases<{ answer: string }, Record<string, never>>('followup.jsonl');
out.push(`## 5. Follow-up writer: ${followup.length} sample answers`, '');
out.push(
  'These have no expected answer. The automatic check is only that a model-written question survives the word check. Whether the question is a good one is read separately.',
  '',
);
for (const c of followup) out.push(`- **${c.id}** (${split(c.split)}, ${c.type}): ${c.input.answer}`);
out.push('');

await writeFile('evals/cases/REVIEW.md', `${out.join('\n')}\n`);
console.log(`Wrote evals/cases/REVIEW.md (${out.length} lines)`);
