import type { StepId } from '../server/llm/types'
import { CEILING_MS, describe, sizeOf, startSettings } from './grid'
import { tieBand } from './rule'
import type { Ranked } from './rule'
import { configId, summarise } from './run'
import type { ResultRow } from './run'
import type { SweepData } from './sweep-data'

const cell = (text: string) => text.replaceAll('|', '\\|').replace(/\s+/g, ' ').trim()
const clip = (text: string, n: number) => (text.length > n ? `${text.slice(0, n - 1)}…` : text)

// Cases one configuration passed (on every run) and another did not, and the
// reverse. A difference is only called real when at least six cases differ
// and all of them differ the same way.
export function paired(a: Array<ResultRow>, b: Array<ResultRow>) {
  const allPass = (rows: Array<ResultRow>) => {
    const m = new Map<string, boolean>()
    for (const r of rows) m.set(r.caseId, (m.get(r.caseId) ?? true) && r.pass)
    return m
  }
  const pa = allPass(a)
  const pb = allPass(b)
  let onlyA = 0
  let onlyB = 0
  for (const [id, ok] of pa) {
    if (!pb.has(id)) continue
    if (ok && !pb.get(id)) onlyA++
    if (!ok && pb.get(id)) onlyB++
  }
  const real = (onlyA >= 6 && onlyB === 0) || (onlyB >= 6 && onlyA === 0)
  return { onlyA, onlyB, real }
}

const TITLE: Record<StepId, string> = {
  selector: 'Menu-picker (`selector`)',
  followup: 'Follow-up writer (`followup`)',
  coverage: 'Coverage judge (`coverage`)',
  revision: 'Revision step (`revision`)',
  verifier: 'Support check (`verifier`)',
}

// The full tables behind SWEEP.md, built from the recorded calls only.
export function sweepMarkdown(
  data: SweepData,
  ranked: Partial<Record<StepId, Array<Ranked>>>,
  chosen: Partial<Record<StepId, Ranked>>,
  notes: { changed: Array<StepId>; drift: string | null; confirmedSteps: Array<StepId>; suppliedQuestions: Array<string> },
): string {
  const run = data.rows.find((r) => r.type === 'run') as { at?: string; env?: Record<string, unknown> } | undefined
  const out: Array<string> = []
  out.push('# Sweep results: every configuration that ran', '')
  out.push(
    'Generated by `pnpm sweep:report` from `evals/results/sweep-ollama.jsonl`. Nothing here is typed by hand. The commentary is in [`SWEEP.md`](../../SWEEP.md).',
    '',
    `- **Recorded:** ${data.results.length} model calls across ${data.configs.size} configurations, starting ${run?.at ?? '?'}.`,
    `- **Machine:** ${String(run?.env?.machine ?? '?')}, ${String(run?.env?.memoryGb ?? '?')} GB, power mode ${String(run?.env?.powerMode ?? '?')}, Ollama ${String(run?.env?.ollamaVersion ?? '?')}.`,
    ...(notes.drift ? [`- **Timing reference:** ${notes.drift}`] : []),
    '',
    'Reading the tables: "cases" is the number of tuning cases that passed on **every** run, out of the number of cases. "Flipped" passed on some runs and failed on others. "Unusable" replies were cut off or not in the required shape. Times are for one model call on this machine. Configurations marked "screened" ran each case once; "confirmed" ran each case three times.',
    '',
  )

  for (const step of Object.keys(TITLE) as Array<StepId>) {
    const list = ranked[step]
    if (!list?.length) continue
    const pick = chosen[step]
    const cases = Math.max(...list.map((c) => c.summary.cases))
    const startId = configId(step, startSettings(step))
    out.push(`## ${TITLE[step]}`, '')
    out.push(
      `Speed ceiling ${CEILING_MS[step] / 1000} s. Configurations within ${tieBand(cases)} case${tieBand(cases) === 1 ? '' : 's'} of the best count as tied.` +
        (notes.confirmedSteps.includes(step) ? '' : ' **Screening run only: the choice below is provisional until the confirmation runs are in.**') +
        (notes.changed.includes(step) ? ' The choice was moved off its first-ranked configuration to keep the app to two models.' : ''),
      '',
    )
    if (pick) {
      out.push(`**Chosen by the rule:** ${describe(pick.settings)} — ${pick.summary.casesAllPass} of ${pick.summary.cases} cases, ${pick.summary.costly} costly errors, median ${pick.summary.medianMs} ms.${pick.eligible ? '' : ' No configuration was eligible; this one has the fewest costly errors.'}`, '')
    }

    // Every configuration, on the single screening run so all are comparable,
    // with the confirmation result alongside where there is one.
    out.push(
      '| | Size | Thinking | Format | Temp | Prompt | Screened: cases | Costly | Fallbacks | Unusable | Median ms (range) | Confirmed: cases (flipped) | Costly | Eligible |',
      '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|',
    )
    const order = new Map(list.map((c, i) => [c.configId, i]))
    const configs = [...data.configs.values()].filter((c) => c.step === step)
    configs.sort((a, b) => (order.get(a.configId) ?? 999) - (order.get(b.configId) ?? 999))
    for (const cfg of configs) {
      const mine = data.results.filter((r) => r.configId === cfg.configId && r.step === step && r.split === 'tune')
      const screen = mine.filter((r) => r.stage === 'screen')
      if (!screen.length) continue
      const s = summarise(screen)
      const hasConfirm = mine.some((r) => r.stage === 'confirm')
      const c3 = hasConfirm ? summarise(mine.filter((r) => r.stage === 'screen' || r.stage === 'confirm')) : null
      const stopped = data.stopped.has(cfg.configId)
      const tags = [
        cfg.configId === startId ? 'start' : '',
        pick?.configId === cfg.configId ? '**chosen**' : '',
        cfg.settings.sampling?.presence_penalty === 0 ? 'no penalty' : '',
      ].filter(Boolean).join(', ')
      const rankedRow = list.find((c) => c.configId === cfg.configId)
      out.push(
        `| ${tags} | ${sizeOf(cfg.settings.model)} | ${cfg.settings.thinking ? 'on' : 'off'} | ${cfg.settings.forceFormat ? 'forced' : 'not forced'} | ${cfg.settings.temperature} | ${cfg.settings.promptVariant} | ` +
          (stopped ? `stopped after ${s.timedCalls} calls` : `${s.casesAllPass} of ${s.cases}`) +
          ` | ${s.costly} | ${s.fallbacks} | ${s.truncated + s.schemaInvalid + s.refusals} | ${s.medianMs} (${s.minMs}–${s.maxMs}) | ` +
          (c3 ? `${c3.casesAllPass} of ${c3.cases} (${c3.casesFlipped})` : '–') +
          ` | ${c3 ? c3.costly : '–'} | ${stopped ? 'no: too slow' : rankedRow ? (rankedRow.eligible ? 'yes' : `no: ${rankedRow.why}`) : '–'} |`,
      )
    }
    out.push('')

    // An accepted follow-up question may simply repeat one of the case file's
    // own questions word for word. That is allowed, but it is not the same as
    // a question in the model's own words, so it is counted.
    if (step === 'followup') {
      const squash = (t: string) => t.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()
      const supplied = new Set(notes.suppliedQuestions.map(squash))
      out.push('| Configuration | Questions accepted | Of those, word for word one of the case file\'s own |', '|---|---|---|')
      for (const cfg of configs) {
        const accepted = data.results.filter((r) => r.configId === cfg.configId && r.step === step && r.split === 'tune' && r.pass)
        if (!accepted.length) continue
        const echoes = accepted.filter((r) => supplied.has(squash(String((r.observed as { question?: string } | null)?.question ?? ''))))
        out.push(`| ${describe(cfg.settings)} | ${accepted.length} | ${echoes.length} |`)
      }
      out.push('')
    }

    // Is the chosen configuration really better than the others, or only tied?
    if (pick) {
      const rowsOf = (id: string) => data.results.filter((r) => r.configId === id && r.step === step && r.split === 'tune' && (r.stage === 'screen' || r.stage === 'confirm'))
      const others = list.filter((c) => c.configId !== pick.configId && !c.stopped).slice(0, 8)
      if (others.length) {
        out.push('**Chosen against the others, case by case** (a difference counts as real only when at least six cases differ, all the same way):', '')
        out.push('| Compared with | Cases only the chosen passed | Cases only the other passed | Verdict |', '|---|---|---|---|')
        for (const o of others) {
          const p = paired(rowsOf(pick.configId), rowsOf(o.configId))
          out.push(`| ${describe(o.settings)} | ${p.onlyA} | ${p.onlyB} | ${p.real ? (p.onlyA > p.onlyB ? 'chosen is better' : 'the other is better') : 'not distinguishable on this set'} |`)
        }
        out.push('')
      }
    }

    // Where the weaker settings fail: real outputs.
    out.push('<details><summary>Failing runs, by configuration (real outputs)</summary>', '')
    for (const cfg of configs) {
      const bad = data.results.filter((r) => r.configId === cfg.configId && r.step === step && r.split === 'tune' && !r.pass && r.outcome !== 'infra_error')
      if (!bad.length) continue
      const byCase = new Map<string, ResultRow>()
      for (const r of bad) if (!byCase.has(r.caseId)) byCase.set(r.caseId, r)
      out.push(`**${describe(cfg.settings)}** — ${byCase.size} case${byCase.size === 1 ? '' : 's'} failed at least once`, '')
      out.push('| Case | Type | Costly | What happened | Raw reply |', '|---|---|---|---|---|')
      for (const r of [...byCase.values()].slice(0, 12)) {
        out.push(`| ${r.caseId} | ${r.caseType} | ${r.costly ? 'yes' : ''} | ${cell(clip(r.detail, 220))} | \`${cell(clip(r.raw, 160)).replaceAll('`', "'")}\` |`)
      }
      if (byCase.size > 12) out.push(`| … | | | ${byCase.size - 12} more | |`)
      out.push('')
    }
    out.push('</details>', '')
  }
  return out.join('\n')
}
