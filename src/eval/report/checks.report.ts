import type { RequiredRow } from '@/eval/checks/required.check';
import type { ResultRow } from '@/eval/run/result-row';
import { summarise } from '@/eval/run/summarise';
import type { RunEnv } from '@/eval/run-env';

type Header = {
  type: 'run';
  runId: string;
  at: string;
  env: RunEnv;
  models: Record<string, unknown>;
  split: string;
  trials: number;
  configFile: string;
  steps: Record<
    string,
    { model: string; thinking: boolean; forceFormat: boolean; promptVariant: string; temperature?: number }
  >;
};
type SelfTest = {
  type: 'selftest';
  step: string;
  cases: number;
  idealPass: number;
  constantName: string;
  constantPass: number;
  wrong: Array<string>;
};

const cell = (text: string) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');
const clip = (text: string, n: number) => (text.length > n ? `${text.slice(0, n - 1)}…` : text);

// Builds CHECKS.md from the rows of one `pnpm check` run and nothing else.
export function checksMarkdown(all: Array<Record<string, unknown>>): string {
  const header = all.find((r) => r.type === 'run') as Header | undefined;
  const required = all.filter((r) => r.type === 'required') as unknown as Array<RequiredRow>;
  const results = all.filter((r) => r.type === 'result') as unknown as Array<ResultRow>;
  const selfTests = all.filter((r) => r.type === 'selftest') as unknown as Array<SelfTest>;
  const date = header?.at.slice(0, 10) ?? 'unknown date';
  const out: Array<string> = [];

  out.push('# Checks', '');
  out.push(
    `Generated by \`pnpm check\` from \`evals/results/${header?.runId}.jsonl\`. Nothing here is typed by hand except where a line says so.`,
    '',
  );
  if (header) {
    out.push(
      `- **When:** ${header.at} (commit \`${header.env.commit}\`${header.env.dirty ? ', with uncommitted changes' : ''})`,
      `- **Machine:** ${header.env.machine}, ${header.env.memoryGb} GB. Power mode: ${header.env.powerMode}. Swap in use: ${header.env.swapUsedMb ?? '?'} MB. Ollama ${header.env.ollamaVersion}.`,
      `- **Settings file:** \`${header.configFile}\``,
      '',
      '| Step | Model | Thinking | Forced format | Prompt | Temperature |',
      '|---|---|---|---|---|---|',
      ...Object.entries(header.steps).map(
        ([step, s]) =>
          `| ${step} | \`${s.model}\` | ${s.thinking ? 'on' : 'off'} | ${s.forceFormat ? 'on' : 'off'} | ${s.promptVariant} | ${s.temperature ?? '–'} |`,
      ),
      '',
    );
  }
  out.push(
    'Results are counts, never bare percentages. All inputs here were typed text; spoken runs are recorded separately in the README.',
    '',
  );

  out.push('## The three required checks', '');
  const groups = new Map<string, Array<RequiredRow>>();
  for (const r of required) groups.set(`${r.check}|${r.name}`, [...(groups.get(`${r.check}|${r.name}`) ?? []), r]);
  if (groups.size === 0) out.push('_Not run in this pass._', '');
  for (const [key, rows] of groups) {
    const [check, name] = key.split('|');
    const passed = rows.filter((r) => r.pass).length;
    const example = rows.find((r) => !r.pass) ?? rows[0];
    if (!example) continue;
    out.push(`### Check ${check}: ${name}`, '');
    out.push(`- **Input:** ${clip(example.input, 400)}`);
    out.push(`- **Expected:** ${example.expected}`);
    out.push(`- **Observed${rows.some((r) => !r.pass) ? ' (a failing run)' : ''}:** ${example.observed}`);
    out.push(`- **Result:** ${passed} of ${rows.length} runs passed. Model \`${example.model}\`, ${date}.`);
    if (example.retrieved) {
      out.push(
        '',
        '| Passage retrieved | Pages | Rank by words | Rank by meaning | Closeness |',
        '|---|---|---|---|---|',
        ...example.retrieved.map(
          (r) => `| ${r.passage} | ${r.pages} | ${r.keywordRank} | ${r.meaningRank ?? '–'} | ${r.cosine ?? '–'} |`,
        ),
      );
    }
    if (example.cited?.excerpt) {
      out.push(
        '',
        `- **Passage cited:** ${example.cited.page}, ${example.cited.heading}: “${example.cited.excerpt}”`,
        "- **Does this passage support the revision point? (a person's yes or no):** _to be filled in by Luke_",
      );
    }
    out.push('');
  }

  out.push('## Each AI step on its case set', '');
  out.push(
    'n is the number of cases; k is the number that passed on every run. "Flipped" cases passed on some runs and failed on others. The floor is what a step that ignores its input would score.',
    '',
    '| Step | Cases passing every run | Flipped | Costly errors | Fallbacks | Unusable replies | Model call time, median (range) | Floor |',
    '|---|---|---|---|---|---|---|---|',
  );
  const steps = [...new Set(results.map((r) => r.step))];
  const NAME: Record<string, string> = {
    selector: 'Menu-picker',
    followup: 'Follow-up writer',
    coverage: 'Coverage judge',
    revision: 'Revision step, alone',
    verifier: 'Support check, alone',
    chain: 'Revision step and support check together',
  };
  for (const step of steps) {
    const rows = results.filter((r) => r.step === step);
    const s = summarise(rows);
    const st = selfTests.find((x) => x.step === step);
    out.push(
      `| ${NAME[step] ?? step} | **${s.casesAllPass} of ${s.cases}** (${s.trialsPerCase} run${s.trialsPerCase === 1 ? '' : 's'} each) | ${s.casesFlipped} | ${s.costly} | ${s.fallbacks} | ${s.truncated + s.schemaInvalid + s.refusals} | ${s.medianMs ?? '–'} ms (${s.minMs ?? '–'}–${s.maxMs ?? '–'}) | ${st ? `${st.constantPass} of ${st.cases} (${st.constantName})` : '–'} |`,
    );
  }
  out.push('');
  for (const st of selfTests) {
    if (st.wrong.length)
      out.push(
        `**Grader problem in ${st.step}:** ${st.wrong.length} expected answers do not pass their own grader: ${st.wrong.join('; ')}`,
        '',
      );
  }

  out.push('### Cases that did not pass every run', '');
  let any = false;
  for (const step of steps) {
    const byCase = new Map<string, Array<ResultRow>>();
    for (const r of results.filter((x) => x.step === step)) byCase.set(r.caseId, [...(byCase.get(r.caseId) ?? []), r]);
    const failing = [...byCase.entries()].filter(([, rows]) => rows.some((r) => !r.pass));
    if (!failing.length) continue;
    any = true;
    out.push(
      `**${NAME[step] ?? step}**`,
      '',
      '| Case | Type | Passed | Costly | What happened (a failing run) |',
      '|---|---|---|---|---|',
    );
    for (const [id, rows] of failing) {
      const bad = rows.find((r) => !r.pass)!;
      out.push(
        `| ${id} | ${bad.caseType} | ${rows.filter((r) => r.pass).length} of ${rows.length} | ${rows.some((r) => r.costly) ? 'yes' : ''} | ${cell(clip(bad.detail, 260))} |`,
      );
    }
    out.push('');
  }
  if (!any) out.push('_None._', '');
  return out.join('\n');
}
